// `medra install --target antigravity`: generate the Antigravity install from the bundled plugin (SPEC §8.13).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { envError, refused, finding, readText, readIf, sha256, writeAtomic } from './core.js';

const here = path.dirname(fileURLToPath(import.meta.url));

/** The bundled plugin copy (published package) or the repository's plugin (development checkout). */
export function pluginDir() {
  for (const dir of [path.join(here, '..', 'plugin'), path.join(here, '..', '..', 'plugins', 'medra')]) {
    if (fs.existsSync(path.join(dir, '.claude-plugin', 'plugin.json'))) return dir;
  }
  throw envError('Bundled medra plugin not found; reinstall the CLI');
}

export const cliVersion = () => JSON.parse(readText(path.join(here, '..', 'package.json'))).version;

function rewriteFrontmatter(text, name) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return text;
  const keep = m[1].split('\n').filter((l) => /^description:/.test(l));
  return `---\nname: ${name}\n${keep.join('\n')}\n---\n${text.slice(m[0].length)}`;
}

function rewriteBody(text, { root: pluginRoot, skillDir }) {
  return text
    .replace(/\$\{CLAUDE_PLUGIN_ROOT\}/g, pluginRoot)
    .replace(/\$\{CLAUDE_SKILL_DIR\}/g, skillDir)
    .replace(/\$ARGUMENTS/g, 'the text the user typed after the command')
    .replace(/medra:([a-z][a-z0-9-]*)/g, 'medra-$1');
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

export function install(projectRoot, { scope = 'workspace', force = false } = {}) {
  const src = pluginDir();
  const version = cliVersion();
  const base = scope === 'global' ? path.join(os.homedir(), '.gemini', 'config') : path.join(projectRoot, '.agents');
  const display = scope === 'global' ? '~/.gemini/config' : '.agents';
  const medraRoot = path.join(base, 'medra');
  const manifestFile = path.join(medraRoot, 'MANIFEST.json');
  const previous = JSON.parse(readIf(manifestFile) ?? '{"files":{}}').files;
  const files = [];
  for (const skill of fs.readdirSync(path.join(src, 'skills')).sort()) {
    const name = `medra-${skill}`;
    const skillDir = `${display}/skills/${name}`;
    for (const file of walk(path.join(src, 'skills', skill))) {
      let text = readText(file);
      if (path.basename(file) === 'SKILL.md') text = rewriteFrontmatter(text, name);
      text = rewriteBody(text, { root: `${display}/medra`, skillDir });
      files.push([path.join(base, 'skills', name, path.relative(path.join(src, 'skills', skill), file)), text]);
    }
  }
  for (const agent of fs.readdirSync(path.join(src, 'agents')).sort()) {
    const text = rewriteBody(rewriteFrontmatter(readText(path.join(src, 'agents', agent)), `medra-${agent.replace(/\.md$/, '')}`), { root: `${display}/medra`, skillDir: `${display}/medra` });
    files.push([path.join(medraRoot, 'agents', agent), text]);
  }
  // Refuse to overwrite files medra did not generate (absent from the manifest, or edited since).
  if (!force) {
    const foreign = files.map(([f]) => f).filter((f) => {
      const cur = readIf(f);
      if (cur === null) return false;
      const key = path.relative(base, f);
      return previous[key] !== sha256(cur);
    });
    if (foreign.length) throw refused(foreign.slice(0, 20).map((f) => finding('install.foreign-file', `${f} exists and was not generated by medra (use --force to replace)`)));
  }
  const manifest = { version, files: Object.fromEntries(files.map(([f, t]) => [path.relative(base, f), sha256(t)])) };
  writeAtomic([...files, [manifestFile, `${JSON.stringify(manifest, null, 2)}\n`], [path.join(medraRoot, 'VERSION'), `${version}\n`]]);
  // Remove files a previous version generated that this version no longer ships.
  for (const key of Object.keys(previous)) if (!manifest.files[key]) fs.rmSync(path.join(base, key), { force: true });
  return { installed: files.length, scope, version };
}
